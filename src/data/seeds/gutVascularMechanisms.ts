type FamilyCode = MechanismFamilyCode;

function node(input: {
  code: string;
  domainCode: DomainCode;
  name: string;
  group: string;
  familyCode: FamilyCode;
  description: string;
  parentCode?: string;
  policy?: ScorePolicy;
  quantitativeScoreByDefault?: boolean;
}): MechanismSeed {
  return {
    code: input.code,
    domainCode: input.domainCode,
    name: input.name,
    description: input.description,
    parentCode: input.parentCode,
    aggregationGroup: input.group,
    scorePolicy: input.policy ?? "SCORABLE",
    sortOrder: 0,
    familyCode: input.familyCode,
    quantitativeScoreByDefault: input.quantitativeScoreByDefault ?? true,
  };
}

